// Builds src/components/shared/categoryIconPaths.ts: each CATEGORY_ICONS key's
// regular-weight Phosphor path. Phosphor's per-icon modules carry all six
// weights (~650 KB for the catalog); one weight is ~80 KB.
// Run after adding an icon to CATEGORY_ICONS: npm run gen:category-icons
import { readFileSync, writeFileSync } from 'node:fs'

const catalog = readFileSync('src/lib/categoryIcons.ts', 'utf8')
const start = catalog.indexOf('export const CATEGORY_ICONS = {')
const keys = [...catalog.slice(start, catalog.indexOf('\n}\n', start)).matchAll(/^ {2}(\w+):/gm)].map((m) => m[1])

const lines = keys.map((key) => {
  const defs = readFileSync(`node_modules/phosphor-react-native/src/defs/${key}.tsx`, 'utf8')
  const regular = defs.slice(defs.indexOf("'regular'"))
  const d = regular.match(/d="([^"]+)"/)?.[1]
  if (!d) throw new Error(`No regular path for ${key}`)
  return `  ${key}: '${d}',`
})

writeFileSync('src/components/shared/categoryIconPaths.ts', `// Generated by scripts/gen-category-icon-paths.mjs. Don't edit.
import type { CategoryIconKey } from '@/src/lib/categoryIcons'

export const CATEGORY_ICON_PATHS: Record<CategoryIconKey, string> = {
${lines.join('\n')}
}
`)
console.log(`${keys.length} icons`)
